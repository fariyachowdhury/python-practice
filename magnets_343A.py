"""
Problem Name: Magnets
Platform: Codeforces (343A)
Problem Link: https://codeforces.com/problemset/problem/343/A

Description:
ম্যাড সায়েন্টিস্ট মাইক কিছু চম্বুক (Magnets) একটার পর একটা সোজা লাইনে দাঁড় করাচ্ছে।
প্রতিটি চুম্বকের দুটি মেরু আছে: প্লাস (+) এবং মাইনাস (-)।
চুম্বকগুলোকে দুইভাবে বসানো যায়:
  - "10" (বাম পাশে +, ডান পাশে -)
  - "01" (বাম পাশে -, ডান পাশে +)

আমরা জানি, সমমেরু (যেমন: - এবং -) পরস্পরকে বিকর্ষণ করে। 
তাই যদি দুটি চুম্বকের বিপরীত বা সমমেরু পাশাপাশি চলে আসে (যেমন: "10" এর পর আবার "10" বসালে 
প্রথমটির ডানপাশের '0' এবং দ্বিতীয়টির বামপাশের '1' আকর্ষণ করে লেগে যায় এবং একটি গ্রুপ বা দল তৈরি করে)।

কিন্তু যদি একটি "10" এর পর "01" রাখা হয়, তবে '0' এবং '0' বিকর্ষণ করে আর তারা আলাদা গ্রুপে পরিণত হয়!

ইনপুট:
- ১ম লাইনে মোট চুম্বকের সংখ্যা (n)।
- পরবর্তী n-টি লাইনে প্রতিটি চুম্বকের দিক দেওয়া থাকবে ("10" অথবা "01")।

আউটপুট:
- মোট কতটি আলাদা চুম্বকের গ্রুপ বা দল গঠিত হলো, সেই সংখ্যাটি প্রিন্ট করতে হবে।
"""

# --- shomadhan---
magnet = int(input())
group = 1

# ১ম চুম্বক ইনপুট নেওয়া হলো
b = input()

# বাকি (magnet - 1) টি চুম্বকের জন্য লুপ
for i in range(magnet - 1):
    x = input()
    if x != b:
        group += 1
        b = x  # সবচেয়ে গুরুত্বপূর্ণ: বর্তমান চুম্বককে 'আগের চুম্বক' হিসেবে সেট করা!

print(group)


